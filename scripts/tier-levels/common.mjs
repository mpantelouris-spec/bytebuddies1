/**
 * Shared helpers for the tier-level builders (Robot Studio modes 11–50).
 * Each builder writes plain data to src/virtual-robot-designer/data/tier-levels/.
 * Run: node scripts/tier-levels/build-all.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(here, '../..');
export const OUT_DIR = path.join(ROOT, 'src/virtual-robot-designer/data/tier-levels');

export const TIERS = ['Easy', 'Medium', 'Hard', 'Advanced'];

/** Deterministic random numbers so a rebuild gives the same levels. */
export function rng(seedText) {
  let h = 2166136261;
  for (const ch of String(seedText)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  let s = h >>> 0;
  const next = () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 4294967296; };
  next.int = (lo, hi) => lo + Math.floor(next() * (hi - lo + 1));
  next.pick = (list) => list[Math.floor(next() * list.length)];
  return next;
}

export function writeData(file, header, exportsObj) {
  const body = Object.entries(exportsObj)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 1).replace(/\n\s*/g, ' ')};`)
    .join('\n\n');
  const text = `/**\n${header.split('\n').map((l) => ` * ${l}`).join('\n')}\n *\n * Generated by scripts/tier-levels — edit the plans there, then rebuild.\n */\n\n${body}\n`;
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, file), text);
  return text.length;
}

/** Split 40 plan rows into the four tiers (10 each). */
export function tierOf(i) { return TIERS[Math.floor(i / 10)]; }
