// Builds src/components/ui/icon-data.js from scripts/ui-icons/emoji-map.json.
// Artwork: Phosphor Icons "fill" weight (MIT, https://phosphoricons.com), from the
// @iconify-json/ph package. Usage: node scripts/ui-icons/build-icons.mjs <path to ph package>
import fs from 'node:fs';
import path from 'node:path';
const phDir = process.argv[2];
if (!phDir) { console.error('usage: node scripts/ui-icons/build-icons.mjs <@iconify-json/ph package folder>'); process.exit(1); }
const ph = JSON.parse(fs.readFileSync(path.join(phDir, 'icons.json'), 'utf8'));
const map = JSON.parse(fs.readFileSync(new URL('./emoji-map.json', import.meta.url), 'utf8'));
const extra = ['caret-down', 'caret-right', 'dots-three', 'x', 'list', 'arrow-left', 'arrows-out', 'arrows-in', 'play', 'stop', 'pause', 'arrow-counter-clockwise', 'skip-forward', 'check'];
const BOLD = new Set(['code', 'hash', 'plus', 'minus', 'check', 'x', 'dots-three', 'list', 'link', 'link-simple', 'arrows-out', 'paperclip']);
const names = [...new Set([...Object.values(map), ...extra])];
const icons = {};
for (const n of names) {
  // A few Phosphor "fill" icons are the symbol cut out of a filled box — use bold for those
  const key = BOLD.has(n) ? `${n}-bold` : ph.icons[`${n}-fill`] ? `${n}-fill` : n;
  if (!ph.icons[key]) throw new Error(`No Phosphor icon ${n}`);
  icons[n] = ph.icons[key].body;
}
// Emoji keys are stored without the U+FE0F variation selector
const emoji = Object.fromEntries(Object.entries(map).map(([e, n]) => [e.replace(/️/g, ''), n]));
const out = `/* Generated by scripts/ui-icons/build-icons.mjs — do not edit by hand.
   Phosphor Icons (fill), MIT licence — https://github.com/phosphor-icons/core */
export const ICON_VIEWBOX = ${ph.width || 256};
export const ICONS = ${JSON.stringify(icons)};
export const EMOJI_TO_ICON = ${JSON.stringify(emoji)};
`;
fs.writeFileSync(new URL('../../src/components/ui/icon-data.js', import.meta.url), out);
console.log(`${names.length} icons, ${Object.keys(emoji).length} emoji mappings, ${Math.round(out.length / 1024)} KB`);
