const DIFFICULTIES = ['Tutorial', 'Easy', 'Easy', 'Medium', 'Medium', 'Medium', 'Hard', 'Hard', 'Hard', 'Expert'];
const CONCEPTS = [
  'sequential blocks', 'variables', 'loops', 'if/else', 'sensors',
  'events', 'functions', 'state machines', 'timing', 'optimization',
];

const catalog = {};
for (const [chassisId, modeIds] of Object.entries(CHASSIS_MODE_MAP)) {
  const defs = ROBOT_MODES[chassisId];
  if (!defs) {
    console.warn(`Missing ROBOT_MODES for ${chassisId}`);
    continue;
  }
  modeIds.forEach((id, i) => {
    const [name, objective] = defs[i] || [`Mode ${i + 1}`, 'Complete the mission.'];
    catalog[id] = {
      id,
      chassisId,
      modeNumber: i + 1,
      name,
      shortName: name.split(' ').slice(0, 2).join(' '),
      desc: objective,
      tagline: objective,
      difficulty: DIFFICULTIES[i],
      modeType: i === 9 ? 'Mastery' : (i < 3 ? 'Training' : 'Mission'),
      programmingConcepts: [CONCEPTS[i], CONCEPTS[(i + 1) % 10]],
      starOne: i < 2 ? 'Complete the objective' : 'Finish the mission',
      starTwo: i < 5 ? 'Hit all checkpoints' : 'Beat the time target',
      starThree: i < 8 ? 'Clean run — no penalties' : 'Perfect mastery run',
      timeEstimateMinutes: [3, 5, 6, 8, 8, 10, 10, 12, 12, 15][i],
      rewardBadge: i === 9 ? `${chassisId}_master` : `${chassisId}_mode_${i + 1}`,
      unlocksNext: i < 9 ? modeIds[i + 1] : null,
    };
  });
}

const out = path.join(root, 'src/virtual-robot-designer/data/chassis-mode-catalog.js');
const content = `/**
 * chassis-mode-catalog.js — Official names, objectives, and metadata for all ${Object.keys(catalog).length} chassis modes.
 * AUTO-GENERATED by scripts/build-chassis-mode-catalog.mjs from the 350-mode design matrix.
 */
export const CHASSIS_MODE_CATALOG = ${JSON.stringify(catalog, null, 2)};

export const CHASSIS_MODE_CATALOG_COUNT = ${Object.keys(catalog).length};

export function getModeCatalogEntry(modeId) {
  return CHASSIS_MODE_CATALOG[modeId] || null;
}

export function applyModeCatalog(mode) {
  if (!mode?.id) return mode;
  const entry = CHASSIS_MODE_CATALOG[mode.id];
  if (!entry) return mode;
  return {
    ...mode,
    name: entry.name,
    shortName: entry.shortName,
    desc: entry.desc,
    tagline: entry.tagline,
    difficulty: entry.difficulty,
    modeType: entry.modeType,
    programmingConcepts: entry.programmingConcepts,
    starRequirements: { one: entry.starOne, two: entry.starTwo, three: entry.starThree },
    estMinutes: entry.timeEstimateMinutes,
    rewardBadge: entry.rewardBadge,
    unlocksNext: entry.unlocksNext,
    catalogName: entry.name,
  };
}
`;

fs.writeFileSync(out, content);
console.log(`Wrote ${Object.keys(catalog).length} mode catalog entries to ${out}`);
