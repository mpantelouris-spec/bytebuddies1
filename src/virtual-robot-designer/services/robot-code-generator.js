/**
 * Production robot config → Python class for Code Studio & simulator education.
 */
import { migrateDesign } from '../config.js';
import { migrateAssembly, listPlacedParts } from './assembly-service.js';
import { computeDesignStats } from './design-service.js';
import { getRegistryPart } from '../data/modular-parts-registry.js';

export function generateRobotClassPython(design) {
  const d = migrateDesign(design);
  const asm = migrateAssembly(d);
  const stats = computeDesignStats(d);
  const parts = listPlacedParts(asm);
  const weightKg = (stats.weight / 10).toFixed(1);
  const speedMs = stats.topSpeedMs;
  const powerW = Math.round(stats.power * 1.2);
  const name = (d.name || 'MyRobot').replace(/[^a-zA-Z0-9_]/g, '') || 'MyRobot';

  const lines = [
    '# Auto-generated by ByteBuddies Robot Invention Lab',
    `# Robot: ${d.name || 'My Invention'}`,
    '# Edit this code, then run in the Test Arena!',
    'from robot import ByteBuddy',
    '',
    `class ${name}:`,
    '    """Your custom robot — parts from the invention lab."""',
    '',
    '    def __init__(self):',
    `        self.weight = ${weightKg}  # kg`,
    `        self.speed = ${speedMs}   # m/s`,
    `        self.power = ${powerW}    # W`,
    `        self.battery = ${stats.battery}  # %`,
    `        self.durability = ${stats.stability}`,
    '        self.bot = ByteBuddy()',
    '',
    '        # Components from your build',
  ];

  const wheels = d.wheels || {};
  lines.push(`        self.wheels = dict(type='${wheels.type || 'standard'}', count=${wheels.count ?? 4}, size='${wheels.size || 'medium'}', motor='${wheels.motor || 'medium'}')`);

  Object.entries(d.sensors || {}).filter(([, v]) => v).forEach(([key]) => {
    lines.push(`        self.${key}_sensor = True`);
  });

  Object.entries(d.tools || {}).filter(([, v]) => v && v !== 'none').forEach(([key, val]) => {
    lines.push(`        self.${key} = ${JSON.stringify(val)}`);
  });

  parts.forEach((p) => {
    const meta = getRegistryPart(p.category, p.partId);
    lines.push(`        # ${p.slotId}: ${meta?.label || p.partId}`);
  });

  lines.push(
    '',
    '    def setup(self):',
    '        self.bot.lights_on()',
  );
  if (d.sensors?.ultrasonic) lines.push('        self.bot.enable_ultrasonic()');
  if (d.sensors?.lidar) lines.push('        self.bot.enable_lidar()');
  if (d.sensors?.camera) lines.push('        self.bot.enable_camera()');

  const fwd = Math.round(40 + stats.speed * 0.4);
  const turn = Math.round(30 + stats.agility * 0.3);

  lines.push(
    '',
    '    def run_mission(self):',
    `        self.bot.forward(${fwd})`,
  );
  if (d.sensors?.ultrasonic) {
    lines.push('        if self.bot.obstacle_ahead():');
    lines.push(`            self.bot.turn_left(${turn})`);
    lines.push(`            self.bot.forward(${Math.round(fwd * 0.5)})`);
  }
  if (d.tools?.pincer || d.tools?.gripper) {
    lines.push('        self.bot.grab()');
    lines.push('        self.bot.wait(0.5)');
    lines.push('        self.bot.release()');
  }
  lines.push(`        self.bot.turn_left(${turn})`);
  lines.push(`        self.bot.forward(${Math.round(fwd * 0.7)})`);
  if (d.abilities?.speedBoost) lines.push(`        self.bot.forward(${fwd})  # turbo boost`);
  lines.push('        self.bot.stop()');
  lines.push('');
  lines.push('');
  lines.push('# Quick run (simulator reads these lines too)');
  lines.push('bot = ByteBuddy()');
  lines.push('bot.lights_on()');
  if (d.sensors?.ultrasonic) lines.push('bot.enable_ultrasonic()');
  if (d.sensors?.lidar) lines.push('bot.enable_lidar()');
  lines.push(`bot.forward(${fwd})`);
  if (d.sensors?.ultrasonic) {
    lines.push('if bot.obstacle_ahead():');
    lines.push(`    bot.turn_left(${turn})`);
    lines.push(`    bot.forward(${Math.round(fwd * 0.5)})`);
  }
  lines.push(`bot.turn_left(${turn})`);
  lines.push(`bot.forward(${Math.round(fwd * 0.7)})`);
  lines.push('bot.stop()');

  return lines.join('\n');
}

/** Back-compat alias used by program-service */
export function generatePythonFromDesign(design) {
  return generateRobotClassPython(design);
}
