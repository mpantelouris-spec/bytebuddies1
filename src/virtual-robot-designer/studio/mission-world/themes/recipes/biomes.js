/** Build a recipe: biome preset + overrides. `layers` go in front of the biome's far scenery. */
export function biome(name, o = {}) {
  const b = BIOMES[name];
  const { layers = [], back, fx, path, sky, lights, ...rest } = o;
  return {
    light: b.light,
    ground: b.ground,
    room: b.room,
    ...rest,
    sky: { ...b.sky, ...sky },
    lights: { ...b.lights, ...lights },
    path: { ...b.path, ...path },
    layers: [...layers, ...(back ?? b.back)],
    fx: fx ?? b.fx,
  };
}
