/**
 * Football match courses — 1v1 skills mode and training.
 */
export const FOOTBALL_COURSE_IDS = new Set([
  'football_fifa', 'football_training', 'football_skills', 'football_championship',
  'football_penalties', 'football_free_kick', 'football_arcade', 'football_street',
  'football_cup_final', 'football_keeper',
]);

export function isFootballCourseId(courseId) {
  return FOOTBALL_COURSE_IDS.has(courseId);
}

/** Always return a full football course object — prevents boxing arena hijacking football. */
export function resolveFootballLabCourse(course, robotConfig = {}) {
  const chassis = robotConfig?.chassisId || '';
  const pick = (id) => FOOTBALL_COURSES.find((c) => c.id === id) || FOOTBALL_COURSES[0];

  if (course?.linkedFootballCourse && isFootballCourseId(course.linkedFootballCourse)) {
    return { ...pick(course.linkedFootballCourse) };
  }

  if (isFootballCourseId(course?.id)) {
    return { ...pick(course.id) };
  }

  if (course && (course.arenaType === 'robot_football' || course.genre === 'football' || course.cat === 'football')) {
    return { ...pick('football_fifa') };
  }

  if (chassis === 'footballbot') {
    return { ...pick('football_fifa') };
  }

  return course;
}

